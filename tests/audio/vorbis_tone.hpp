inline std::vector<std::byte> VorbisTone() {
    constexpr std::string_view kAlphabet =
        "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    std::vector<std::byte> bytes;
    std::uint32_t bits = 0;
    int bitCount = 0;
    for (const char c : kVorbisToneBase64) {
        if (c == '=') {
            break;
        }
        bits = (bits << 6U) | static_cast<std::uint32_t>(kAlphabet.find(c));
        bitCount += 6;
        if (bitCount >= 8) {
            bitCount -= 8;
            bytes.push_back(static_cast<std::byte>((bits >> bitCount) & 0xFFU));
        }
    }
    return bytes;
}

